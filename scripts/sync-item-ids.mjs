import fs from "node:fs/promises";
import path from "node:path";
const OUTPUT = path.resolve("data/item-ids.txt");
const SOURCES = [process.env.ITEM_ID_SOURCE,
"https://raw.githubusercontent.com/jiiselfryelf/Growtopia/main/growtopia-item-id.txt",
"https://raw.githubusercontent.com/badewen/Growtopia-Things/main/item_id_list.txt"].filter(Boolean);
function parseIds(text) {
 const ids = new Set();
 for (const raw of text.split(/\r?\n/)) {
  const line = raw.trim(); if (!line || line.startsWith("#")) continue;
  const m = line.match(/^(\d+)\s*(?::|\s|$)/);
  if (m) { const n = Number(m[1]); if (Number.isSafeInteger(n) && n >= 0) ids.add(n); }
 }
 return [...ids].sort((a,b)=>a-b);
}
await fs.mkdir(path.dirname(OUTPUT), {recursive:true});
let previous = ""; try { previous = await fs.readFile(OUTPUT,"utf8"); } catch {}
for (const url of SOURCES) {
 try {
  console.log(`Fetching IDs from ${url}`);
  const r = await fetch(url,{signal:AbortSignal.timeout(20000),headers:{"user-agent":"GROWERA-texture-collector/2.0","accept":"text/plain,*/*"}});
  if (!r.ok) throw new Error(`HTTP ${r.status}`);
  const ids = parseIds(await r.text());
  if (ids.length < 1000) throw new Error(`Only parsed ${ids.length} IDs; refusing overwrite`);
  await fs.writeFile(OUTPUT,`# Generated by scripts/sync-item-ids.mjs; community list may be incomplete/outdated.\n${ids.join("\n")}\n`);
  console.log(`Saved ${ids.length} unique IDs.`); process.exit(0);
 } catch(e) { console.warn(`Source failed: ${url}: ${e.message}`); }
}
if (parseIds(previous).length) { console.warn("Remote sources failed; keeping existing list."); process.exit(0); }
console.error("No valid remote list and no usable local list."); process.exit(1);
